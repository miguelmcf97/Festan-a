import type { Metadata } from "next";
import { loadConversation } from "@/server/ai/agent";
import { getAnonKey, getCurrentUser } from "@/server/auth";
import { getT } from "@/server/i18n";
import { getAiUsage } from "@/server/services/ai-usage";
import { PlannerChat } from "./planner-chat";

export async function generateMetadata(): Promise<Metadata> {
  const { t } = await getT();
  return { title: t("Planejar com IA", "Plan with AI") };
}

export default async function PlanejarPage({ searchParams }: { searchParams: Promise<{ q?: string; c?: string }> }) {
  const { q, c } = await searchParams;
  const user = await getCurrentUser();
  const { t } = await getT();
  const anon = user ? null : await getAnonKey(false);
  const [existing, usage] = await Promise.all([
    c ? loadConversation(c, user?.id ?? null, anon) : Promise.resolve(null),
    getAiUsage({ userId: user?.id ?? null, anonKey: anon, role: user?.role }),
  ]);
  const engineLabel =
    process.env.ANTHROPIC_API_KEY && process.env.AI_PROVIDER !== "demo-rules"
      ? null
      : t("Modo demonstração: respostas geradas por regras, sem modelo de linguagem.", "Demo mode: replies are generated by rules (in Portuguese), without a language model.");

  return (
    <PlannerChat
      initialQuery={existing || (usage.remaining !== null && usage.remaining <= 0) ? null : (q ?? null)}
      initial={existing}
      user={user ? { name: user.name, role: user.role } : null}
      engineNotice={engineLabel}
      initialUsage={usage}
    />
  );
}
